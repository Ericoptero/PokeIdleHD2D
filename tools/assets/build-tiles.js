#!/usr/bin/env node
/**
 * Converts Pokemon DS Map Studio tilesets into everything the engine and the artists need:
 *
 *   public/generated/tiles/<slug>/obj/<category>/<name>.obj|.mtl   for Blender and review
 *   public/generated/tiles/<slug>/tex/*.png                        the source textures
 *   public/generated/tiles/<slug>/catalog.json                     classified model index
 *   public/generated/tiles/<slug>/pack.json + pack.bin             the runtime pack
 *
 * The OBJ files are the artist-facing product; the pack is what the game actually loads, because parsing 260
 * OBJ files in the browser at boot would blow the 6-second budget on its own.
 *
 * Usage:  node tools/assets/build-tiles.js [--only <slug>] [--list]
 */

import { readdirSync, mkdirSync, writeFileSync, copyFileSync, rmSync, existsSync } from 'node:fs';
import { join, dirname, basename, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePdsts, tileToTriangles } from './pdsts.js';
import { classifyTile, orientationSignature, SMART_UNITS, SMART_SLOT_NAMES, packSignature } from './classify.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');
const PDSMS = '/Users/ericnantes/Downloads/Pokemon-DS-Map-Studio/src/main/resources/tilesets';
const OUT = join(REPO, 'public', 'generated', 'tiles');

/** Which tilesets we ship, and under what slug. AdAstra first — it is the house style. */
const SETS = [
  ['bw2-adastra', 'Black_-_White_2/Tileset_2_-_Overworld_(by_AdAstra)'],
  ['bw2-cave', 'Black_-_White_2/Cave'],
  ['bw2-chargestone', 'Black_-_White_2/Chargestone_Cave'],
  ['bw2-twist', 'Black_-_White_2/Tileset_294_-_Twist_Mountain'],
  ['bw2-brom', 'Black_-_White_2/Tileset_2_-_Overworld_(by_Brom)'],
  ['bw-overworld', 'Black_-_White/Overworld'],
  ['hgss-overworld', 'Heart_Gold_-_Soul_Silver/Tileset_2_-_Overworld'],
  ['hgss-newbark-houses', 'Heart_Gold_-_Soul_Silver/Tileset_25_-_New_Bark_Town_Houses_(by_Monkeyboy0)'],
  ['hgss-safari', 'Heart_Gold_-_Soul_Silver/Tileset_75_-_Safari_Zone_(by_Mikelan98)'],
  ['pt-house-indoor', 'Platinum/Tileset_20_-_House_Indoor'],
  ['pt-forest', 'Platinum/Tileset_53_-_Forest_(by_Jiboule)'],
  ['pt-overworld-7', 'Platinum/Tileset_7_-_Overworld_(by_Jiboule)'],
  ['sylvan-town', 'Various/Sylvan_Town_(by_Anarlaurendil)'],
];

const findPdsts = (dir) => readdirSync(dir).filter((f) => f.endsWith('.pdsts')).map((f) => join(dir, f))[0];

/** DS materials store alpha 0..31; 31 is opaque. */
const isTranslucent = (m) => (m.ALPHA ?? 31) < 31;

function writeObj(path, name, groups, materials, _textureIds) {
  const lines = [`# ${name}`, `# generated by tools/assets/build-tiles.js — do not edit`,
    `mtllib ${basename(path).replace(/\.obj$/, '.mtl')}`, `o ${name}`];
  const mtl = [`# ${name}`];
  let vBase = 1;

  groups.forEach((g, gi) => {
    const matName = (materials[g.textureId]?.MAT_NAME || `tex${g.textureId}`).replace(/\s+/g, '_');
    const img = materials[g.textureId]?.IMG_NAME || 'PLACEHOLDER.png';
    const m = materials[g.textureId] ?? {};
    mtl.push(`newmtl ${matName}`, 'Ka 1.000 1.000 1.000', 'Kd 1.000 1.000 1.000',
      'Ks 0.000 0.000 0.000', `d ${((m.ALPHA ?? 31) / 31).toFixed(3)}`, 'illum 1',
      `map_Kd ../../tex/${img}`, `map_d ../../tex/${img}`, '');

    const n = g.position.length / 3;
    for (let i = 0; i < n; i++) lines.push(`v ${g.position[i * 3].toFixed(5)} ${g.position[i * 3 + 1].toFixed(5)} ${g.position[i * 3 + 2].toFixed(5)}`);
    for (let i = 0; i < n; i++) lines.push(`vt ${g.uv[i * 2].toFixed(5)} ${(-g.uv[i * 2 + 1]).toFixed(5)}`);
    for (let i = 0; i < n; i++) lines.push(`vn ${g.normal[i * 3].toFixed(4)} ${g.normal[i * 3 + 1].toFixed(4)} ${g.normal[i * 3 + 2].toFixed(4)}`);
    lines.push(`g ${name}_${gi}`, `usemtl ${matName}`);
    for (let i = 0; i < n; i += 3) {
      const a = vBase + i, b = vBase + i + 1, c = vBase + i + 2;
      lines.push(`f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}`);
    }
    vBase += n;
  });

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, lines.join('\n') + '\n');
  writeFileSync(path.replace(/\.obj$/, '.mtl'), mtl.join('\n') + '\n');
}

function buildSet(slug, relDir) {
  const dir = join(PDSMS, relDir);
  if (!existsSync(dir)) return { slug, skipped: 'missing' };
  const file = findPdsts(dir);
  if (!file) return { slug, skipped: 'no .pdsts' };

  const { materials, tiles, smartGrids } = parsePdsts(file);
  const outDir = join(OUT, slug);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(join(outDir, 'tex'), { recursive: true });

  const usedImages = new Set();
  for (const m of materials) if (m.IMG_NAME) usedImages.add(m.IMG_NAME);
  for (const img of usedImages) {
    const src = join(dir, img);
    if (existsSync(src)) copyFileSync(src, join(outDir, 'tex', img));
  }

  // slot lookup: tileIndex -> { setId, slot } from the smart-drawing templates
  const slotOf = new Map();
  const autotileSets = smartGrids.map((grid, gi) => {
    const flat = [];
    for (let n = 0; n < 13; n++) {
      const x = n % 5, y = Math.floor(n / 5);
      const tileIndex = grid[x]?.[y] ?? -1;
      flat.push(tileIndex);
      if (tileIndex >= 0 && !slotOf.has(tileIndex)) slotOf.set(tileIndex, { set: gi, slot: n });
    }
    return { id: `set${gi}`, index: gi, grid, slots: flat, name: null };
  });

  // ---- models -------------------------------------------------------------
  const models = [];
  const nameCounts = new Map();
  const packChunks = [];
  let packOffset = 0;

  for (const tile of tiles) {
    const { groups, bounds } = tileToTriangles(tile);
    const w = tile.WIDTH ?? 1, h = tile.HEIGHT ?? 1;
    if (!groups.length) {
      models.push({ id: tile.index, empty: true, source: tile.OBJNAME ?? null });
      continue;
    }
    // A flat "floor" — zero vertical extent — authored metres above its own cell reads as a
    // cliff-top surface to `classifyTile` below (`bounds.min[1] >= 0.5` -> tag `raised`), but a
    // handful of PDSMS tiles (AdAstra's `grass`/`stone_path`/`cliff_top` variants) are the exact
    // same flat ground mesh as their `baseY:0` twin, just modeled a second time up on the cliff
    // shelf for convenience while authoring the source `.pdsts` — with nothing marking that they
    // were never meant to be placed at ground level. `InstancedWorld.composeMatrix`
    // (`@/tiles/instanced.js`) places every instance at the raw placement Y with no `baseY`
    // compensation, so one of these picked from the Studio's asset library (which selects by
    // name, unlike `tiles.find()`'s own `raised` exclusion) and painted at `y:0` floats the
    // whole plane in the air with nothing underneath — the confirmed bug this replaces.
    // Re-based here, at the source, rather than only at runtime (`groundBaseYToZero`,
    // `@/tiles/materials.js`) so a rebuild ships the correct geometry outright; that runtime
    // pass stays as a safety net for a tileset rebuilt without this guard.
    if (bounds.min[1] >= 0.5 && bounds.max[1] - bounds.min[1] < 0.01) {
      const drop = bounds.min[1];
      for (const g of groups) for (let i = 1; i < g.position.length; i += 3) g.position[i] -= drop;
      bounds.min[1] -= drop; bounds.max[1] -= drop;
    }
    // The dominant texture (most vertices) is what the tile actually looks like.
    const dominant = groups.reduce((a, g) => (g.position.length > (a?.position.length ?? -1) ? g : a), null);
    const cls = classifyTile(tile, materials, bounds, dominant?.textureId);
    const slot = slotOf.get(tile.index);

    let name = cls.base;
    if (slot) name += `_${SMART_SLOT_NAMES[slot.slot]}`;
    else if (cls.orientation) name += `_${cls.orientation}`;
    const seen = (nameCounts.get(name) ?? 0) + 1;
    nameCounts.set(name, seen);
    const unique = seen === 1 ? name : `${name}_v${seen}`;

    const objPath = join(outDir, 'obj', cls.category, `${unique}.obj`);
    writeObj(objPath, unique, groups, materials, tile.TIDS);

    // runtime pack: one interleaved Float32 block per material group
    const packGroups = groups.map((g) => {
      const n = g.position.length / 3;
      const buf = new Float32Array(n * 11);
      for (let i = 0; i < n; i++) {
        const o = i * 11;
        buf[o] = g.position[i * 3]; buf[o + 1] = g.position[i * 3 + 1]; buf[o + 2] = g.position[i * 3 + 2];
        buf[o + 3] = g.normal[i * 3]; buf[o + 4] = g.normal[i * 3 + 1]; buf[o + 5] = g.normal[i * 3 + 2];
        buf[o + 6] = g.uv[i * 2]; buf[o + 7] = g.uv[i * 2 + 1];
        buf[o + 8] = g.color[i * 3]; buf[o + 9] = g.color[i * 3 + 1]; buf[o + 10] = g.color[i * 3 + 2];
      }
      const bytes = Buffer.from(buf.buffer);
      const entry = { material: g.textureId, offset: packOffset, count: n };
      packChunks.push(bytes); packOffset += bytes.length;
      return entry;
    });

    models.push({
      id: tile.index,
      name: unique,
      obj: relative(outDir, objPath).replaceAll('\\', '/'),
      source: tile.OBJNAME ?? null,
      category: cls.category,
      subcategory: cls.subcategory,
      orientation: cls.orientation,
      tags: cls.tags,
      biomes: cls.biomes,
      collision: cls.collision,
      w, h,
      /** World Y the tile's own geometry starts at; non-zero for cliff-top surfaces. */
      baseY: +bounds.min[1].toFixed(4),
      /**
       * PDSMS "global texture mapping": the tile's baked UVs cover only one cell of a
       * larger pattern and the editor derives the rest from world position. We keep the
       * baked UVs and hand the runtime the per-cell step so an InstancedMesh can offset
       * them per instance — that is what stops a big lawn reading as one stamped tile.
       */
      globalUv: !!tile.GLOBALMAPPING,
      uvScale: tile.GLOBALMAPPING ? (tile.GLOBALTEXSCALE ?? 1) : 0,
      bounds: { min: bounds.min.map((v) => +v.toFixed(4)), max: bounds.max.map((v) => +v.toFixed(4)) },
      materials: [...new Set(groups.map((g) => g.textureId))],
      autotile: slot ? { set: `set${slot.set}`, slot: slot.slot, name: SMART_SLOT_NAMES[slot.slot] } : null,
      signature: orientationSignature(groups, bounds, w, h),
      groups: packGroups,
      tris: groups.reduce((a, g) => a + g.position.length / 9, 0),
    });
  }

  // Name each autotile set after the majority subcategory of its member tiles.
  for (const set of autotileSets) {
    const names = set.slots.filter((i) => i >= 0).map((i) => models.find((m) => m.id === i)?.subcategory).filter(Boolean);
    const tally = new Map();
    for (const n of names) tally.set(n, (tally.get(n) ?? 0) + 1);
    set.name = [...tally.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? set.id;
    set.bySignature = {};
    set.slots.forEach((tileIndex, n) => {
      if (tileIndex >= 0) set.bySignature[packSignature(SMART_UNITS[n])] = tileIndex;
    });
  }

  const catalog = {
    tileset: slug,
    source: relative(PDSMS, file).replaceAll('\\', '/'),
    unitsPerCell: 1,
    axis: 'y-up, +x east, +z south',
    materials: materials.map((m, i) => ({
      id: i,
      image: m.IMG_NAME ?? null,
      name: m.MAT_NAME ?? null,
      alpha: m.ALPHA ?? 31,
      translucent: isTranslucent(m),
      bothFaces: !!m.BOTHFACE,
      vertexColors: !!m.VERTEX_COLORS,
      fog: !!m.FOG,
      tilingU: m.TEX_TILING_U ?? 1,
      tilingV: m.TEX_TILING_V ?? 1,
      uniformNormals: !!m.NORMALORIENT,
    })),
    autotileSets,
    models,
  };
  writeFileSync(join(outDir, 'catalog.json'), JSON.stringify(catalog, null, 1));

  // pack.json duplicates the light half of the catalog so the runtime never parses OBJs.
  const pack = {
    tileset: slug,
    stride: 11,
    materials: catalog.materials,
    autotileSets: autotileSets.map(({ id, name, slots, bySignature }) => ({ id, name, slots, bySignature })),
    models: models.map((m) => m.empty ? { id: m.id, empty: true } : ({
      id: m.id, name: m.name, category: m.category, subcategory: m.subcategory,
      orientation: m.orientation, tags: m.tags, biomes: m.biomes, collision: m.collision,
      w: m.w, h: m.h, baseY: m.baseY, bounds: m.bounds, autotile: m.autotile, groups: m.groups,
      globalUv: m.globalUv, uvScale: m.uvScale,
    })),
  };
  writeFileSync(join(outDir, 'pack.json'), JSON.stringify(pack));
  writeFileSync(join(outDir, 'pack.bin'), Buffer.concat(packChunks));

  const byCat = {};
  for (const m of models) if (!m.empty) byCat[m.category] = (byCat[m.category] ?? 0) + 1;
  return {
    slug, tiles: tiles.length, models: models.filter((m) => !m.empty).length,
    materials: materials.length, autotileSets: autotileSets.length,
    packBytes: packOffset, byCat,
    unknown: models.filter((m) => m.category === 'unknown').map((m) => m.source),
  };
}

const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;
mkdirSync(OUT, { recursive: true });

const report = [];
for (const [slug, dir] of SETS) {
  if (only && slug !== only) continue;
  try {
    report.push(buildSet(slug, dir));
  } catch (err) {
    report.push({ slug, error: err.message });
    console.error(`✗ ${slug}: ${err.stack}`);
  }
}
writeFileSync(join(OUT, 'index.json'), JSON.stringify({
  sets: report.filter((r) => !r.error && !r.skipped).map((r) => r.slug),
  built: report,
}, null, 1));

for (const r of report) {
  if (r.error) { console.log(`✗ ${r.slug}: ${r.error}`); continue; }
  if (r.skipped) { console.log(`— ${r.slug}: ${r.skipped}`); continue; }
  const unknown = r.unknown.length ? `  UNKNOWN:${[...new Set(r.unknown)].join(',')}` : '';
  console.log(`✓ ${r.slug.padEnd(22)} ${String(r.models).padStart(4)} models  ${String(r.materials).padStart(3)} mats  ` +
    `${String(r.autotileSets).padStart(2)} autotile  ${(r.packBytes / 1024).toFixed(0).padStart(5)}KB  ` +
    Object.entries(r.byCat).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k}:${v}`).join(' ') + unknown);
}
